import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { readFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const base = "http://127.0.0.1:8788";
const decrypted = spawnSync("powershell.exe", ["-NoLogo", "-NoProfile", "-NonInteractive", "-Command", "$env:PSModulePath=Join-Path $PSHOME 'Modules'; $s=(Get-Content -LiteralPath $env:SUPERMEMO_CREDENTIAL -Raw).Trim() | ConvertTo-SecureString; try {[Console]::Out.Write([System.Net.NetworkCredential]::new('', $s).Password)} finally {$s.Dispose()}"], { windowsHide: true, encoding: "utf8", env: { ...process.env, SUPERMEMO_CREDENTIAL: join(root, ".tools/secrets/supermemo-token.dpapi") } });
if (decrypted.status !== 0 || !decrypted.stdout.trim()) throw new Error("Credential unlock failed");
const headers = { Authorization: `Bearer ${decrypted.stdout.trim()}` }; decrypted.stdout = "";
const request = (path, options = {}) => fetch(base + path, { ...options, signal: AbortSignal.timeout(15000) });
const check = (valid, description) => { if (!valid) throw new Error(description); };
const latest = readdirSync(join(root, "backups")).filter((name) => /^\d{4}-/.test(name)).sort().at(-1);
const backup = join(root, "backups", latest);
const memos = JSON.parse(readFileSync(join(backup, "memos.json"), "utf8")).memos;
const manifest = JSON.parse(readFileSync(join(backup, "manifest.json"), "utf8"));
const imageMemo = memos.find((memo) => !memo.isDeleted && memo.contentJson.content.some((node) => node.type === "image"));
check(imageMemo, "No image memo available for production verification");
const imagePath = imageMemo.contentJson.content.find((node) => node.type === "image").attrs.src;
for (const path of ["/api/v1/memos?searchScope=body", `/api/v1/memos/${imageMemo.id}`, imagePath, "/api/v1/tags"]) {
  check((await request(path)).status === 401, "Anonymous data access was not refused");
}
const session = await request("/api/v1/auth/session");
const sessionBody = await session.json();
check(sessionBody.authenticated === false && sessionBody.authRequired === true, "Production session must require login");
const page = await request("/memo"); const html = await page.text();
check(page.ok && html.includes("/assets/") && !html.includes("/@vite/client"), "Production assets were not served");
const detail = await request(`/api/v1/memos/${imageMemo.id}`, { headers });
check(detail.ok, "Authorized memo access failed");
const { memo } = await detail.json(); check(memo.id === imageMemo.id, "Canonical memo ID differs");
const image = await request(imagePath, { headers }); check(image.ok, "Authorized image access failed");
const bytes = new Uint8Array(await image.arrayBuffer());
check(manifest.resources.some((item) => item.bytes === bytes.length && item.sha256 === createHash("sha256").update(bytes).digest("hex")), "Restored and served image differ");
const rpc = { jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "get_memo", arguments: { memoId: memo.id } } };
const rpcHeaders = { "Content-Type": "application/json", Accept: "application/json, text/event-stream", "MCP-Protocol-Version": "2025-11-25" };
check((await request("/mcp", { method: "POST", headers: rpcHeaders, body: JSON.stringify(rpc) })).status === 401, "Anonymous MCP was not refused");
const mcp = await request("/mcp", { method: "POST", headers: { ...rpcHeaders, ...headers }, body: JSON.stringify(rpc) });
const result = await mcp.json(); check(result.result?.structuredContent?.memo?.id === memo.id, "Production MCP data differs");
console.log(JSON.stringify({ success: true, runtime: "compiled-worker-local", checks: ["production assets", "login required", "anonymous memo/search/tag/image/MCP refused", "authorized canonical memo", "authorized image SHA256", "MCP shared ID"] }));
